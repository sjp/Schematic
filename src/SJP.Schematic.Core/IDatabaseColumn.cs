using LanguageExt;

namespace SJP.Schematic.Core;

/// <summary>
/// Represents a database column present on a table or view.
/// </summary>
public interface IDatabaseColumn
{
    /// <summary>
    /// The name of a column within a table or view.
    /// </summary>
    /// <value>A column name.</value>
    Identifier Name { get; }

    /// <summary>
    /// Determines whether a column can store <see langword="null" /> values.
    /// </summary>
    /// <value><see langword="true" /> if this column can store <see langword="null" /> values; otherwise, <see langword="false" />.</value>
    bool IsNullable { get; }

    /// <summary>
    /// Determines whether the column is omitted from the expansion of <c>SELECT *</c>. Such a column
    /// still exists and can be named explicitly, in an <c>INSERT</c> column list or a key, but a
    /// projection shaped like a row of the table must leave it out.
    /// </summary>
    /// <value><see langword="true" /> if this column is hidden from <c>SELECT *</c>; otherwise, <see langword="false" />.</value>
    bool IsHidden { get; }

    /// <summary>
    /// The default applied to a column when omitted on an <c>INSERT</c> statement, including the
    /// name of the constraint carrying it and a classification of what its expression evaluates to.
    /// </summary>
    /// <value>The default for a column, if available.</value>
    Option<DatabaseDefaultValue> Default { get; }

    /// <summary>
    /// An expression that creates a default value for a column when omitted on an <c>INSERT</c> statement.
    /// A convenience over <see cref="Default"/>, which carries the same expression alongside the
    /// constraint name and classification.
    /// </summary>
    /// <value>The default value for a column, if available.</value>
    Option<string> DefaultValue => Default.Map(static def => def.Definition);

    /// <summary>
    /// The database column data type.
    /// </summary>
    /// <value>A column data type.
    /// </value>
    IDbType Type { get; }

    /// <summary>
    /// Where the values of this column come from: written to it, computed by the database from an
    /// expression, or generated by the database as an identity.
    /// </summary>
    /// <value>The source of the column's values.</value>
    ColumnValueSource ValueSource { get; }
}