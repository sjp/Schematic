using System;
using System.Collections.Generic;
using Moq;
using NUnit.Framework;
using SJP.Schematic.Core;
using SJP.Schematic.Tests.Utilities;

namespace SJP.Schematic.Oracle.Tests;

internal static class OracleDatabaseUserDefinedTypeProviderTests
{
    [Test]
    public static void Ctor_GivenNullConnection_ThrowsArgNullException()
    {
        var identifierDefaults = Mock.Of<IIdentifierDefaults>();

        Assert.That(
            () => new OracleDatabaseUserDefinedTypeProvider(null, identifierDefaults),
            Throws.ArgumentNullException.With.Property(nameof(ArgumentException.ParamName)).EqualTo("connection")
        );
    }

    [Test]
    public static void Ctor_GivenNullIdentifierDefaults_ThrowsArgNullException()
    {
        var connection = Mock.Of<IDbConnectionFactory>();

        Assert.That(
            () => new OracleDatabaseUserDefinedTypeProvider(connection, null),
            Throws.ArgumentNullException.With.Property(nameof(ArgumentException.ParamName)).EqualTo("identifierDefaults")
        );
    }

    [Test]
    public static void GetUserDefinedType_GivenNullTypeName_ThrowsArgNullException()
    {
        var connection = Mock.Of<IDbConnectionFactory>();
        var identifierDefaults = Mock.Of<IIdentifierDefaults>();

        var typeProvider = new OracleDatabaseUserDefinedTypeProvider(connection, identifierDefaults);

        Assert.That(
            () => typeProvider.GetUserDefinedType(null),
            Throws.ArgumentNullException.With.Property(nameof(ArgumentException.ParamName)).EqualTo("typeName")
        );
    }

    [Test]
    public static void BuildSpecification_GivenSpecificationLines_ReturnsJoinedLines()
    {
        var lines = new[] { "TYPE t AS OBJECT (\n", "  a NUMBER\n", ")" };

        var specification = OracleDatabaseUserDefinedTypeProvider.BuildSpecification(lines);

        Assert.That(specification.UnwrapSome(), Is.EqualTo("TYPE t AS OBJECT (\n  a NUMBER\n)"));
    }

    [Test]
    public static void BuildSpecification_GivenOnlyWhitespace_ReturnsNone()
    {
        var lines = new[] { " ", null, "\n" };

        var specification = OracleDatabaseUserDefinedTypeProvider.BuildSpecification(lines);

        Assert.That(specification, OptionIs.None);
    }

    // Oracle stores a wrapped specification as a single ALL_SOURCE row holding the whole wrapped text.
    [Test]
    public static void BuildSpecification_GivenWrappedSpecification_ReturnsUnwrappedSpecification()
    {
        var lines = new[] { WrappedTypeSpecification };

        var specification = OracleDatabaseUserDefinedTypeProvider.BuildSpecification(lines);

        Assert.That(specification.UnwrapSome(), Is.EqualTo(ExpectedUnwrappedTypeSpecification));
    }

    // generated by DBMS_DDL.CREATE_WRAPPED on Oracle 23ai from:
    // create or replace type wrap_probe_type as object (attr_one number(10, 2), attr_two varchar2(50))
    private const string WrappedTypeSpecification = "type wrap_probe_type wrapped \n"
        + "a000000\n"
        + "369\n"
        + "abcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\nabcd\n"
        + "d\n"
        + "4f 8d\n"
        + "7nXwA9y8c/He9JVISM175AJ+wO0wg5n0dLhcFpbyVuOWFpeu8vCWJlZaXLh0K6W/m8Ayy8xQ\n"
        + "uHS9vRj+/sdcpZmBMsCyJXwhUMx8JXfMpm0HRvjVRq05rRJXOYjedasRJ2WmpuuQbyo=\n";

    private const string ExpectedUnwrappedTypeSpecification = "TYPE wrap_probe_type AS OBJECT (ATTR_ONE NUMBER(10, 2), ATTR_TWO VARCHAR2(50))";
}
